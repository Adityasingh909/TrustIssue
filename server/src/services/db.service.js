const { prisma, formatPrismaError } = require('../utils/prisma');
const {
  UserInputSchema,
  AgentInputSchema,
  TestCaseInputSchema,
  TestRunCreateSchema,
  TestRunUpdateSchema,
  FindingInputSchema,
  ReportInputSchema
} = require('../utils/validators');

class DatabaseService {
  // ==========================================
  // USERS
  // ==========================================

  async createUser(input) {
    const validated = UserInputSchema.parse(input);
    try {
      return await prisma.user.create({
        data: validated
      });
    } catch (err) {
      throw formatPrismaError(err);
    }
  }

  async getUserByEmail(email) {
    return prisma.user.findUnique({
      where: { email }
    });
  }

  // ==========================================
  // AGENTS
  // ==========================================

  async createAgent(input) {
    const validated = AgentInputSchema.parse(input);
    try {
      return await prisma.agent.create({
        data: validated
      });
    } catch (err) {
      throw formatPrismaError(err);
    }
  }

  async getAgentById(id) {
    const agent = await prisma.agent.findUnique({
      where: { id }
    });
    if (!agent) {
      const err = new Error(`Agent not found with id: ${id}`);
      err.status = 404;
      throw err;
    }
    return agent;
  }

  async listAgents() {
    return prisma.agent.findMany({
      orderBy: { createdAt: 'desc' }
    });
  }

  // ==========================================
  // TEST CASES
  // ==========================================

  async createTestCase(input) {
    const validated = TestCaseInputSchema.parse(input);
    try {
      return await prisma.testCase.create({
        data: validated
      });
    } catch (err) {
      throw formatPrismaError(err);
    }
  }

  async getTestCaseById(id) {
    const testCase = await prisma.testCase.findUnique({
      where: { id }
    });
    if (!testCase) {
      const err = new Error(`TestCase not found with id: ${id}`);
      err.status = 404;
      throw err;
    }
    return testCase;
  }

  async listTestCases(category = null) {
    const where = category ? { category } : {};
    return prisma.testCase.findMany({
      where,
      orderBy: { createdAt: 'desc' }
    });
  }

  // ==========================================
  // TEST RUNS & FINDINGS (TRANSACTIONS)
  // ==========================================

  async createTestRun(input) {
    const validated = TestRunCreateSchema.parse(input);
    try {
      return await prisma.testRun.create({
        data: {
          agentId: validated.agentId,
          testCaseId: validated.testCaseId,
          status: 'QUEUED'
        },
        include: {
          agent: { select: { id: true, name: true, provider: true, model: true } },
          testCase: { select: { id: true, title: true, category: true, severity: true } }
        }
      });
    } catch (err) {
      throw formatPrismaError(err);
    }
  }

  /**
   * Records test run outcome atomically using a transaction.
   * Ensures that updating test run status and recording security findings succeed together.
   * Distinguishes security failure (FAILED) from execution error (ERROR),
   * and accommodates INCONCLUSIVE and SKIPPED outcomes.
   */
  async recordTestRunOutcome(runId, updateData, findings = []) {
    const validatedUpdate = TestRunUpdateSchema.parse(updateData);

    return prisma.$transaction(async (tx) => {
      // 1. Verify TestRun exists
      const existing = await tx.testRun.findUnique({ where: { id: runId } });
      if (!existing) {
        const err = new Error(`TestRun not found with id: ${runId}`);
        err.status = 404;
        throw err;
      }

      // 2. Update TestRun
      const updatedRun = await tx.testRun.update({
        where: { id: runId },
        data: {
          status: validatedUpdate.status || existing.status,
          startedAt: validatedUpdate.startedAt || existing.startedAt,
          completedAt: validatedUpdate.completedAt || new Date(),
          actualResponse: validatedUpdate.actualResponse ?? existing.actualResponse,
          evaluationResult: validatedUpdate.evaluationResult ?? existing.evaluationResult,
          durationMs: validatedUpdate.durationMs ?? existing.durationMs,
          errorMessage: validatedUpdate.errorMessage ?? existing.errorMessage
        }
      });

      // 3. Atomically create any findings generated by security failures
      const createdFindings = [];
      if (Array.isArray(findings) && findings.length > 0) {
        for (const findingInput of findings) {
          const validatedFinding = FindingInputSchema.parse({
            ...findingInput,
            testRunId: runId
          });
          const created = await tx.finding.create({
            data: validatedFinding
          });
          createdFindings.push(created);
        }
      }

      return {
        ...updatedRun,
        findings: createdFindings
      };
    });
  }

  async getTestRunById(id) {
    const run = await prisma.testRun.findUnique({
      where: { id },
      include: {
        agent: true,
        testCase: true,
        findings: true
      }
    });
    if (!run) {
      const err = new Error(`TestRun not found with id: ${id}`);
      err.status = 404;
      throw err;
    }
    return run;
  }

  async listTestRuns(filters = {}) {
    const where = {};
    if (filters.agentId) where.agentId = filters.agentId;
    if (filters.testCaseId) where.testCaseId = filters.testCaseId;
    if (filters.status) where.status = filters.status;

    return prisma.testRun.findMany({
      where,
      include: {
        agent: { select: { id: true, name: true, provider: true } },
        testCase: { select: { id: true, title: true, category: true, severity: true } },
        findings: { select: { id: true, severity: true, title: true } }
      },
      orderBy: { createdAt: 'desc' }
    });
  }

  // ==========================================
  // REPORTS
  // ==========================================

  async createReport(input) {
    const validated = ReportInputSchema.parse(input);
    try {
      return await prisma.report.create({
        data: validated
      });
    } catch (err) {
      throw formatPrismaError(err);
    }
  }

  async getReportById(id) {
    const report = await prisma.report.findUnique({
      where: { id },
      include: { user: { select: { id: true, email: true } } }
    });
    if (!report) {
      const err = new Error(`Report not found with id: ${id}`);
      err.status = 404;
      throw err;
    }
    return report;
  }
}

module.exports = new DatabaseService();
